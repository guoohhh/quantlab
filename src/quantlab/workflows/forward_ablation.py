FORWARD_GOVERNANCE_VERSION = "round5-independent-ablation-v2"
FORWARD_PROMPT_VERSION = "forward-raw-single-prompt-v1"
FORWARD_SCHEMA_VERSION = "forward-ablation-v4"


class RawForwardForecast(BaseModel):
    up_probability: float = Field(ge=0, le=1)
    flat_probability: float = Field(ge=0, le=1)
    down_probability: float = Field(ge=0, le=1)
    action: str
    confidence: float = Field(ge=0, le=1)


def create_round3_forward_cohort(
    settings: Settings,
    *,
    frozen_at: datetime | None = None,
) -> dict[str, Any]:
    if frozen_at is not None:
        raise ValueError("forward cohort frozen_at is generated by the server")
    protocol = register_round3_protocol(settings)
    server_frozen_at = datetime.now(UTC)
    governed_hash = hashlib.sha256(
        f"{protocol['protocol_hash']}:{FORWARD_GOVERNANCE_VERSION}".encode("utf-8")
    ).hexdigest()
    return StrategyEvidenceRepository(
        settings.resolve(settings.get("system.database_path"))
    ).create_forward_cohort(
        protocol_version=f"{ROUND3_PROTOCOL_VERSION}+{FORWARD_GOVERNANCE_VERSION}",
        protocol_hash=governed_hash,
        frozen_at=server_frozen_at,
        minimum_matured_samples=30,
        payload={
            "horizons": [5, 20],
            "historical_backfill_allowed": False,
            "protocol_hash_recalculated": protocol_hash(),
            "governance_version": FORWARD_GOVERNANCE_VERSION,
            "server_clock": "UTC",
        },
    )


def freeze_forward_ablation_sample(
    settings: Settings,
    *,
    cohort_id: str,
    symbol: str,
    horizon_days: int,
    account_id: str | None = None,
    quote_service: QuoteService | None = None,
    context_pack: AnalysisContextPack | dict[str, Any] | None = None,
    committee_runner: Callable[..., dict[str, Any]] | None = None,
    raw_llm_runner: Callable[..., dict[str, Any]] | None = None,
    registration_origin: str = "internal",
    formal: bool = False,
    minimum_trust_level: DataTrustLevel | str = DataTrustLevel.SERVER_OBSERVED,
    as_of: date | None = None,
    frozen_role_policy: dict[str, Any] | None = None,
    frozen_statistical_model_id: str | None = None,
    use_active_statistical_model: bool = True,
    variant_policy: dict[str, Any] | None = None,
    sample_key_context_fingerprint: str | None = None,
) -> list[dict[str, Any]]:
    if horizon_days not in {5, 20}:
        raise ValueError("forward ablation horizon must be 5 or 20 days")
    service = quote_service or QuoteService.from_settings(settings)
    asset_type = _asset_type(settings, symbol)
    quote = service.get(
        symbol,
        asset_type=asset_type,
        as_of=as_of,
        require_authoritative=True,
        minimum_trust=minimum_trust_level,
    )
    if formal and (as_of is None or quote.as_of != as_of):
        raise ValueError("formal forward registration requires the exact signal-day quote")
    if context_pack is None:
        existing = EvidenceRepository(
            settings.resolve(settings.get("system.database_path"))
        ).latest_context(symbol, as_of=quote.as_of.isoformat())
        if existing and date.fromisoformat(str(existing.get("as_of"))[:10]) != quote.as_of:
            existing = None
        context_payload = existing or build_analysis_context_pack(
            settings,
            symbol=symbol,
            as_of=quote.as_of,
            asset_type=asset_type.value,
            market_quote=quote,
            account_id=account_id,
            include_events=True,
            save=True,
        )
        pack = AnalysisContextPack.model_validate(context_payload)
    else:
        pack = (
            context_pack
            if isinstance(context_pack, AnalysisContextPack)
            else AnalysisContextPack.model_validate(context_pack)
        )
    if pack.symbol != symbol or pack.as_of > quote.as_of:
        raise ValueError("forward context does not match the authoritative start quote")
    if formal and pack.as_of != quote.as_of:
        raise ValueError("formal forward context must be frozen for the exact signal day")
    deterministic_max_weight = float(settings.get("risk.max_single_position", 0.15))
    runner = committee_runner or run_context_committee
    resolved_role_policy = _resolve_frozen_role_policy(frozen_role_policy, pack)
    try:
        committee = runner(
            settings,
            pack=pack,
            deterministic_max_weight=deterministic_max_weight,
            idempotency_key=(
                f"forward:{cohort_id}:{symbol}:{quote.as_of.isoformat()}:{horizon_days}"
            ),
            role_policy_override=resolved_role_policy,
        )
    except Exception as exc:
        committee = {
            "action": "review_required",
            "confidence": 0.0,
            "suggested_weight_max": 0.0,
            "degraded_roles": ["committee"],
            "failure_type": type(exc).__name__,
        }
    raw_llm = (raw_llm_runner or run_raw_forward_llm)(
        settings,
        pack=pack,
        horizon_days=horizon_days,
        idempotency_key=(
            f"raw-forward:{cohort_id}:{symbol}:{quote.as_of.isoformat()}:{horizon_days}"
        ),
    )
    predictions = _execute_variants(
        settings,
        pack=pack,
        committee=committee,
        horizon_days=horizon_days,
        deterministic_max_weight=deterministic_max_weight,
        raw_llm=raw_llm,
        frozen_statistical_model_id=frozen_statistical_model_id,
        use_active_statistical_model=use_active_statistical_model,
        variant_policy=variant_policy,
    )
    due_at = TradingCalendarService.from_settings(settings).due_at(
        quote.as_of,
        horizon_days,
        formal=formal,
        minimum_trust=minimum_trust_level,
    )
    sample_key = _sample_key(
        cohort_id=cohort_id,
        symbol=symbol,
        account_id=account_id,
        as_of=quote.as_of.isoformat(),
        horizon_days=horizon_days,
        context_fingerprint=sample_key_context_fingerprint or pack.fingerprint,
    )
    return StrategyEvidenceRepository(
        settings.resolve(settings.get("system.database_path"))
    ).register_forward_sample(
        cohort_id=cohort_id,
        sample_key=sample_key,
        symbol=symbol,
        as_of=quote.as_of,
        due_at=due_at,
        horizon_days=horizon_days,
        predictions=predictions,
        context_fingerprint=pack.fingerprint,
        start_price=quote.raw_price,
        quote_source=quote.source,
        quote_provider=quote.provider or quote.source,
        quote_version=quote.source_version,
        quote_fingerprint=quote.quote_fingerprint,
        strategy_version=str(settings.get("strategies.a_share_v4.protocol_version", "unknown")),
        prompt_version=FORWARD_PROMPT_VERSION,
        governance_version=FORWARD_GOVERNANCE_VERSION,
        account_id=account_id,
        registration_origin=registration_origin,
    )


def run_raw_forward_llm(
    settings: Settings,
    *,
    pack: AnalysisContextPack,
    horizon_days: int,
    idempotency_key: str,
) -> dict[str, Any]:
    provider = build_provider(settings.values.get("llm", {}))
    governed = GovernedLLMProvider(
        provider,
        EvidenceRepository(settings.resolve(settings.get("system.database_path"))),
        context_id=pack.context_id,
        context_fingerprint=pack.fingerprint,
        task_id=idempotency_key,
        budget=budget_from_settings(settings.values.get("llm", {})),
        prompt_version=FORWARD_PROMPT_VERSION,
        schema_version=FORWARD_SCHEMA_VERSION,
        governance_version="raw-llm-no-role-governance",
    )
    system = (
        "You are one frozen raw forecasting model. Do not call tools, roles, committees, "
        "quantitative models or governance weights. Use only the supplied compact evidence."
    )
    prompt = json.dumps(
        {
            "horizon_days": horizon_days,
            "context": pack.llm_payload(),
            "required": "probabilities and one action",
        },
        ensure_ascii=False,
        sort_keys=True,
    )
    try:
        result = asyncio.run(
            await_with_provider_close(
                governed,
                governed.structured(system, prompt, RawForwardForecast),
            )
        )
    except Exception as exc:
        return {
            "probabilities": {"up": 1 / 3, "flat": 1 / 3, "down": 1 / 3},
            "action": "observe",
            "confidence": 0.0,
            "complete": False,
            "failure_type": type(exc).__name__,
            "provider": getattr(provider, "provider_name", "unknown"),
            "model": getattr(provider, "model", "unknown"),
        }
    actual_provider = str(
        getattr(result, "_llm_provider", getattr(provider, "provider_name", "unknown"))
    )
    actual_model = str(
        getattr(result, "_llm_model", getattr(provider, "model", "unknown"))
    )
    production_provider = (
        actual_provider.lower() not in {"mock", "fallback", "unknown"}
        and _provider_runtime_is_production(provider)
    )
    if not production_provider:
        return {
            "probabilities": {"up": 1 / 3, "flat": 1 / 3, "down": 1 / 3},
            "action": "observe",
            "confidence": 0.0,
            "complete": False,
            "failure_type": "non_production_llm_provider",
            "provider": actual_provider,
            "model": actual_model,
        }
    return {
        "probabilities": _normalize(
            {
                "up": result.up_probability,
                "flat": result.flat_probability,
                "down": result.down_probability,
            }
        ),
        "action": result.action,
        "confidence": result.confidence,
        "complete": True,
        "provider": actual_provider,
        "model": actual_model,
    }


