def _variant_costs(settings: Settings, sample: dict[str, Any]) -> dict[str, dict[str, float]]:
    repository = StrategyEvidenceRepository(
        settings.resolve(settings.get("system.database_path"))
    )
    with repository.connect() as db:
        rows = db.execute(
            """
            SELECT variant,target_weight,actually_triggered
            FROM forward_ablation_predictions
            WHERE cohort_id=? AND sample_key=? AND horizon_days=?
            """,
            (sample["cohort_id"], sample["sample_key"], int(sample["horizon_days"])),
        ).fetchall()
    round_trip_rate = (
        float(settings.get("costs.stock.commission_rate", 0.00025)) * 2
        + float(settings.get("costs.stock.stamp_duty_rate", 0.0005))
        + float(settings.get("costs.stock.transfer_fee_rate", 0.00001)) * 2
        + float(settings.get("costs.stock.slippage_bps", 10.0)) * 2 / 10_000
    )
    return {
        str(row["variant"]): {
            "target_weight": float(row["target_weight"]),
            "turnover": float(row["target_weight"]) if row["actually_triggered"] else 0.0,
            "cost_pct": float(row["target_weight"]) * round_trip_rate * 100.0,
        }
        for row in rows
    }


